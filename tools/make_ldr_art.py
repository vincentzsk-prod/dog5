"""Generate firmware/loader/ldr_art.h: the update loader's two pictures.

  LDR_HEAD  the dog head mark: the 240 px black-and-white favicon, cropped to its ring and reduced to 96 px,
            1 bit a pixel (white)
  LDR_WORD  the DØG-5 pixel wordmark: Yatra One at 48 px on a 1-bit grid, Sun Yellow letters, a 1 px black
            outline, a hard Acid Chartreuse shadow 4 px down and right; 2 bits a pixel
            (0 background or outline, 2 yellow, 3 chartreuse)

Rows are MSB first. Needs Pillow, NumPy and SciPy (host only; nothing here runs on the unit).

  tools/make_ldr_art.py FAVICON_240.png YatraOne-Regular.ttf [OUT.h]
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import binary_dilation

HEAD = 96            # the head's size on the loader screen
CROP = (16, 230)     # the ring of the 240 px favicon (rows and columns)
WORD_PX, SHADOW = 48, 4


def head(path):
    a = np.asarray(Image.open(path).convert("L"))[CROP[0]:CROP[1], CROP[0]:CROP[1]]
    im = Image.fromarray(a).resize((HEAD, HEAD), Image.BOX)
    return np.asarray(im) > 127


def word(font):
    f = ImageFont.truetype(str(font), WORD_PX)
    l, t, r, b = f.getbbox("DØG-5")
    m = Image.new("L", (r - l + 4, b - t + 4), 0)
    ImageDraw.Draw(m).text((2 - l, 2 - t), "DØG-5", font=f, fill=255)
    m = np.pad(np.asarray(m) > 140, SHADOW + 2)
    h, w = m.shape
    out = np.zeros((h, w), np.uint8)
    sh = np.zeros_like(m)
    sh[SHADOW:, SHADOW:] = m[:h - SHADOW, :w - SHADOW]
    out[sh] = 3
    out[binary_dilation(m, np.ones((3, 3)))] = 0
    out[m] = 2
    ys, xs = np.nonzero(out)
    return out[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def pack(img, bpp):
    h, w = img.shape
    per = 8 // bpp
    data = []
    for row in img:
        for b in range((w + per - 1) // per):
            v = 0
            for k in range(per):
                x = b * per + k
                if x < w:
                    v |= int(row[x]) << (8 - bpp - k * bpp)
            data.append(v)
    return data


def carray(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in data[i:i + 24]) + ",")
    return "\n".join(lines + ["};", ""])


def main(argv):
    if len(argv) < 2:
        raise SystemExit(__doc__)
    hd, wd = head(argv[0]), word(argv[1])
    out = Path(argv[2]) if len(argv) > 2 else Path(__file__).resolve().parent.parent / "firmware/loader/ldr_art.h"
    text = ("/* SPDX-License-Identifier: GPL-3.0-only\n * Copyright (C) 2026 Vincent Kruger (DØG-5: the dog head and the wordmark) */\n"
            "/* The update loader's two pictures, generated by tools/make_ldr_art.py from the brand art. Do not edit by hand.\n"
            f" * LDR_HEAD: the dog head mark, {hd.shape[1]} x {hd.shape[0]}, 1 bit a pixel (white), rows MSB first.\n"
            f" * LDR_WORD: the DØG-5 pixel wordmark, {wd.shape[1]} x {wd.shape[0]}, 2 bits a pixel (0 background, 2 yellow, 3 chartreuse; the black\n"
            " *   outline between them is 0), rows MSB first. */\n"
            f"#define LDR_HEAD_W {hd.shape[1]}u\n#define LDR_HEAD_H {hd.shape[0]}u\n"
            f"#define LDR_WORD_W {wd.shape[1]}u\n#define LDR_WORD_H {wd.shape[0]}u\n"
            + carray("LDR_HEAD", pack(hd, 1)) + carray("LDR_WORD", pack(wd, 2)))
    out.write_text(text)
    print(f"{out}: head {hd.shape[1]}x{hd.shape[0]} ({len(pack(hd, 1))} B), word {wd.shape[1]}x{wd.shape[0]} ({len(pack(wd, 2))} B)")


if __name__ == "__main__":
    main(sys.argv[1:])
