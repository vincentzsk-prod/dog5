"""Writes the host scripts for the TAPE listening kit (listen/tape/) and its measurements: the GROWL kit's four
sources (tests/drive/make_scripts.py, the same notes and patches) x CHEW 0/25/50/75/100 % (raw 0, 32, 64, 95, 127),
the same sources with GROWL and CHEW together, knob sweeps, the aliasing proof, CHEW in and out of the bypass, and
the hardest case for the sanitizer. Parameter numbers are the obv_params.h enum. Every source starts at 2600 ms
(after the 2.4 s splash)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
LEVEL = {0: 0, 25: 32, 50: 64, 75: 95, 100: 127}
P = dict(O1_WAVE=0, O2_WAVE=4, O2_FINE=11, CUTOFF=12, RESO=13, FENV_AMT=14, FTYPE=16, AA=24, AS=26, AR=27, MODE=38,
         UNI_N=39, GLIDE=41, VINTAGE=42, VOLUME=45, GRL_BIAS=52, GRL_TONE=53, GROWL=54, DLY_MIX=58, REV_MIX=62,
         CHEW=64, WOWFLT=65, HISS=66, DROPS=67)
T0 = 2600


def prog(n, params):                      # program change, then the params 1 ms later (before any audio block)
    return [f"{T0} midi 0xC0 {n} 0"] + [f"{T0 + 1} param {P[k]} {v}" for k, v in params]


def note(t, n, dur, vel=100):
    return [f"{t} midi 0x90 {n} {vel}", f"{t + dur} midi 0x80 {n} 0"]


SOURCES = {   # (as tests/drive/make_scripts.py)
    "lowsaw": (prog(31, [("O2_WAVE", 0), ("CUTOFF", 110), ("RESO", 0), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
               + note(T0 + 100, 36, 3000), 6500),
    "chord": (prog(31, [("CUTOFF", 90), ("RESO", 10), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
              + sum((note(T0 + 100, n, 3000) for n in (48, 52, 55, 59)), []), 6500),
    "bass": (prog(0, []) + sum((note(T0 + 100 + 250 * i, n, 200) for i, n in
                                enumerate([33, 33, 45, 33, 36, 33, 31, 33] * 2)), []), 7500),
    "lead": (prog(31, [("MODE", 3), ("CUTOFF", 127), ("RESO", 5), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
             + note(T0 + 100, 79, 300) + note(T0 + 400, 81, 300) + note(T0 + 700, 84, 2000) + note(T0 + 2700, 76, 400),
             6500),
}
COMBOS = [(25, 25), (50, 50), (100, 50), (50, 100), (100, 100)]   # (GROWL %, CHEW %)


def write(name, lines, end):                 # the host reads events in file order: sort by time (stable)
    lines = sorted(lines, key=lambda l: int(l.split()[0]))
    with open(os.path.join(HERE, name + ".txt"), "w") as f:
        f.write("# generated by tests/tape/make_scripts.py\n" + "\n".join(lines) + f"\n{end} end\n")


def knob_sweep(t):                           # KNOB 1 (encoder 2), one detent every 60 ms, 0 -> 100 % -> 0
    out = []
    for i in range(64): out.append(f"{t} enc 2 1"); t += 60
    t += 500
    for i in range(64): out.append(f"{t} enc 2 -1"); t += 60
    return out


TO_TAPE = [f"{T0 + 20 + 40 * i} btn 2" for i in range(4)] + [f"{T0 + 200} expect page 14"]   # FX x4: DRIVE..TAPE

for src, (lines, end) in SOURCES.items():
    for pct, raw in LEVEL.items():
        write(f"src_{src}_{pct:03d}", lines + [f"{T0 + 1} param {P['CHEW']} {raw}"], end)
        if pct:                              # the same with the hiss off: the music alone (the hiss = the difference)
            write(f"nohiss_{src}_{pct:03d}", lines + [f"{T0 + 1} param {P['CHEW']} {raw}", f"{T0 + 1} param {P['HISS']} 0"], end)
    for g, c in COMBOS:
        base = lines + [f"{T0 + 1} param {P['GROWL']} {LEVEL[g]}"]
        write(f"combo_{src}_g{g:03d}c000", base, end)
        write(f"combo_{src}_g{g:03d}c{c:03d}", base + [f"{T0 + 1} param {P['CHEW']} {LEVEL[c]}"], end)
        write(f"combonh_{src}_g{g:03d}c{c:03d}", base + [f"{T0 + 1} param {P['CHEW']} {LEVEL[c]}", f"{T0 + 1} param {P['HISS']} 0"], end)

# the knob: the chord held 9 s on the TAPE page while CHEW is turned 0 -> 100 % -> 0 one detent at a time
sw = [l for l in SOURCES["chord"][0] if " midi 0x80 " not in l] + [f"{T0 + 9100} midi 0x80 {n} 0" for n in (48, 52, 55, 59)]
write("sweep_chord", sw + TO_TAPE + knob_sweep(T0 + 600), T0 + 10500)
sw = prog(31, [("MODE", 3), ("CUTOFF", 127), ("RESO", 5), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
sw += [f"{T0 + 300} midi 0x90 84 100", f"{T0 + 9100} midi 0x80 84 0"]
write("sweep_lead", sw + TO_TAPE + knob_sweep(T0 + 600), T0 + 10500)
# CHEW in and out of the bypass on a held chord: 0 -> 50 % at once, back to 0, to 100 % at once, back to 0
tg = [l for l in SOURCES["chord"][0] if " midi 0x80 " not in l] + [f"{T0 + 11000} midi 0x80 {n} 0" for n in (48, 52, 55, 59)]
tg += [f"{T0 + 1000} param {P['CHEW']} 64", f"{T0 + 4000} param {P['CHEW']} 0",
       f"{T0 + 6500} param {P['CHEW']} 127", f"{T0 + 9000} param {P['CHEW']} 0"]
write("toggle_chord", tg, T0 + 12000)
# the aliasing proof: one saw (OSC 2 off, VINTAGE 0: an exact harmonic comb), the filter wide open, MONO, a high note
# held 3 s at CHEW 0 and 100 %, the hiss and the dropouts off (noise is not aliasing): C6 (1046.5 Hz), C7 (2093 Hz)
for nm, n in (("c6", 84), ("c7", 96)):
    base = prog(31, [("MODE", 3), ("O2_WAVE", 0), ("CUTOFF", 127), ("RESO", 0), ("FENV_AMT", 64), ("AS", 127),
                     ("AR", 40), ("VINTAGE", 0), ("HISS", 0), ("DROPS", 0)]) + note(T0 + 100, n, 3000)
    for pct in (0, 100):
        for wf in (0, 64):                   # wow alone, and wow + flutter (the default)
            write(f"alias_{nm}_{pct:03d}_wf{wf:03d}", base + [f"{T0 + 1} param {P['CHEW']} {LEVEL[pct]}",
                                                         f"{T0 + 1} param {P['WOWFLT']} {wf}"], T0 + 3600)
# the hardest the synth can drive it: 8-voice unison saws at VOLUME 127, delay and reverb on, GROWL 127, then a POLY
# cluster; CHEW and the secondaries stepped through everything (for the sanitizer build: no overflow anywhere)
w = prog(31, [("MODE", 2), ("CUTOFF", 127), ("RESO", 0), ("FENV_AMT", 64), ("AS", 127), ("UNI_N", 8), ("VOLUME", 127),
              ("DLY_MIX", 127), ("REV_MIX", 127), ("GROWL", 127), ("HISS", 127), ("DROPS", 127)])
w += note(T0 + 100, 36, 3300)
w += [f"{T0 + 3500} param {P['MODE']} 0"] + sum((note(T0 + 3600, n, 3000) for n in (36, 43, 48, 52, 55, 60, 64, 67)), [])
w += [f"{T0 + 100 + 50 * i} param {P['CHEW']} {(i * 37) % 128}" for i in range(130)]
w += [f"{T0 + 100 + 250 * i} param {P['WOWFLT']} {(i * 53) % 128}" for i in range(26)]
write("worst_voices", w, T0 + 7000)
print("scripts written to", HERE)
