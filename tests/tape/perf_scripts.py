"""The Psych Chain's CPU scripts (dog5-docs/PERF-BASELINE.md), for tests/perf_callgrind.sh: program 1 switched to
POLY, a held Cmaj7 (C4 E4 G4 B4) from 3.0 to 9.0 s, the stage(s) under test switched on at 2.7 s, the end at 9.5 s
(the stage is on for 299,880 frames). A stage's cost = (Ir on - Ir off) / 299,880, host x86-64 instructions/sample.
Parameter numbers: the obv_params.h enum."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
P = dict(MODE=38, GROWL=54, DLY_MIX=58, REV_MIX=62, CHEW=64)
STAGES = {
    "off": [],
    "growl": [("GROWL", 100)],
    "dly": [("DLY_MIX", 60)],
    "rev": [("REV_MIX", 60)],
    "chew": [("CHEW", 100)],
    "all3": [("GROWL", 100), ("DLY_MIX", 60), ("REV_MIX", 60)],
    "all4": [("GROWL", 100), ("DLY_MIX", 60), ("REV_MIX", 60), ("CHEW", 100)],
}
for name, on in STAGES.items():
    lines = ["2600 midi 0xC0 0 0", f"2601 param {P['MODE']} 0"]
    lines += [f"2700 param {P[k]} {v}" for k, v in on]
    lines += [f"3000 midi 0x90 {n} 100" for n in (60, 64, 67, 71)]
    lines += [f"9000 midi 0x80 {n} 0" for n in (60, 64, 67, 71)]
    with open(os.path.join(HERE, f"perf_{name}.txt"), "w") as f:
        f.write("# generated by tests/tape/perf_scripts.py\n" + "\n".join(lines) + "\n9500 end\n")
