"""Writes the host scripts for the ALLEY listening kit (listen/bbd/) and its measurements: four sources that leave
room for echoes x five ALLEY settings (and dry), the same SYNC setting on the old delay for an A/B, GROWL and CHEW
together with ALLEY, a tap-tempo demonstration on the panel (REC on the BBD page), and knob turns while the repeats
ring. Parameter numbers are the obv_params.h enum. Every source starts at 2600 ms (after the 2.4 s splash)."""
import math
import os
HERE = os.path.dirname(os.path.abspath(__file__))
P = dict(O1_WAVE=0, O2_WAVE=4, CUTOFF=12, RESO=13, FENV_AMT=14, AA=24, AD=25, AS=26, AR=27, MODE=38, GROWL=54,
         DLY_TIME=55, DLY_FB=56, DLY_TONE=57, DLY_MIX=58, REV_MIX=62, CHEW=64, ALLEY=68, FINE=69, SPREAD=70)
T0 = 2600
FS = 44100
BBD_T = [min(32634, round(10.0 * 74.0 ** ((max(i, 1) - 1) / 126) * FS / 1000)) for i in range(128)]


def alley(ms):                               # (ALLEY, FINE) for a time, as obv_fx.h alley_index works it out
    n = ms * FS / 1000
    i = max(k for k in range(1, 127) if BBD_T[k] <= n)
    f = min(127, int(((n - BBD_T[i]) * 128 + (BBD_T[i + 1] - BBD_T[i]) // 2) // (BBD_T[i + 1] - BBD_T[i])))
    return i, f


def prog(n, params):                         # program change, then the params 1 ms later (before any audio block)
    return [f"{T0} midi 0xC0 {n} 0"] + [f"{T0 + 1} param {P[k]} {v}" for k, v in params]


def note(t, n, dur, vel=100):
    return [f"{t} midi 0x90 {n} {vel}", f"{t + dur} midi 0x80 {n} 0"]


SOURCES = {
    # a short Cmaj7 stab, twice (INIT, POLY: two detuned saws a voice), the room between for the repeats
    "stab": (prog(31, [("CUTOFF", 90), ("RESO", 10), ("FENV_AMT", 64), ("AS", 127), ("AR", 30)])
             + sum((note(T0 + 100, n, 150) for n in (48, 52, 55, 59)), [])
             + sum((note(T0 + 2600, n, 150) for n in (48, 52, 55, 59)), []), 7600),
    # program 1 Red Pill as voiced: one bar of the GROWL / CHEW kits' 8th-note riff on A1, then silence
    "bass": (prog(0, []) + sum((note(T0 + 100 + 250 * i, n, 200) for i, n in
                                enumerate([33, 33, 45, 33, 36, 33, 31, 33])), []), 7600),
    # a bright mono lead, filter wide open: G5 A5 C6 short, then E5
    "lead": (prog(31, [("MODE", 3), ("CUTOFF", 127), ("RESO", 5), ("FENV_AMT", 64), ("AS", 127), ("AR", 30)])
             + note(T0 + 100, 79, 180) + note(T0 + 400, 81, 180) + note(T0 + 700, 84, 350) + note(T0 + 2600, 76, 250),
             7600),
    # program 11 Slapback Strut as voiced (its base is SUB BASS): quarter notes at 120 BPM, short
    "slap": (prog(10, []) + sum((note(T0 + 100 + 500 * i, n, 120) for i, n in enumerate([36, 36, 43, 36, 39, 36, 34, 36])), []),
             7600),
}

S = {   # name: (ALLEY, FINE, FEEDBK, TONE, MIX, PINGPONG, what)
    "dbl": alley(25) + (0, 127, 64, 0, "25 ms, one repeat, mono: doubling"),
    "slap": alley(90) + (15, 100, 90, 0, "90 ms, a short tail, mono: slapback"),
    "sync": (0, 0, 60, 70, 70, 127, "SYNC 1/8. at 120 BPM (375 ms), FEEDBK 60, ping-pong: the old delay's own setting"),
    "long": alley(600) + (85, 70, 70, 127, "600 ms, FEEDBK 85, ping-pong: long and dark"),
    "runaway": alley(300) + (124, 90, 60, 64, "300 ms, FEEDBK 124: self-oscillation, half ping-pong"),
}


def settings(name):
    a, f, fb, tone, mix, sp, _ = S[name]
    return [f"{T0 + 1} param {P['ALLEY']} {a}", f"{T0 + 1} param {P['FINE']} {f}", f"{T0 + 1} param {P['DLY_FB']} {fb}",
            f"{T0 + 1} param {P['DLY_TONE']} {tone}", f"{T0 + 1} param {P['DLY_MIX']} {mix}",
            f"{T0 + 1} param {P['SPREAD']} {sp}"]


def write(name, lines, end):                 # the host reads events in file order: sort by time (stable)
    lines = sorted(lines, key=lambda l: int(l.split()[0]))
    with open(os.path.join(HERE, name + ".txt"), "w") as f:
        f.write("# generated by tests/bbd/make_scripts.py\n" + "\n".join(lines) + f"\n{end} end\n")


TO_BBD = [f"{T0 + 20} btn 2", f"{T0 + 60} btn 2", f"{T0 + 150} expect page 12"]   # FX x2: DRIVE, BBD DELAY

for src, (lines, end) in SOURCES.items():
    write(f"src_{src}_dry", lines, end)
    for s in S:
        write(f"src_{src}_{s}", lines + settings(s), end)
    # the old delay, its own parameters only (the same as "sync"; the old build has no bytes 68-70)
    write(f"old_{src}_sync", lines + [f"{T0 + 1} param {P['DLY_FB']} 60", f"{T0 + 1} param {P['DLY_MIX']} 70"], end)

# GROWL and CHEW with ALLEY, as they will be played (the chain: GROWL -> output stage -> ALLEY -> reverb -> CHEW)
COMBOS = {"g050_sync": [("GROWL", 64)], "sync_c050": [("CHEW", 64)], "g050_sync_c050": [("GROWL", 64), ("CHEW", 64)],
          "g100_runaway_c100": [("GROWL", 127), ("CHEW", 127)]}
for src in ("stab", "bass", "lead"):
    lines, end = SOURCES[src]
    for nm, extra in COMBOS.items():
        s = "runaway" if "runaway" in nm else "sync"
        ex = [f"{T0 + 1} param {P[k]} {v}" for k, v in extra]
        write(f"combo_{src}_{nm}", lines + settings(s) + ex, end)
        write(f"combo_{src}_{nm}_noalley", lines + ex, end)    # the same without ALLEY: what ALLEY adds

# tap tempo on the panel: the bass riff looped (8ths at 120 BPM), on the BBD page; WAG (REC, button 13) tapped
# 4x at 500 ms (a quarter: the echo lands on the beat), then 4x at 375 ms while the repeats ring (a dotted 8th: the
# repeats bend to it), then 3x at 1000 ms (slower than 740 ms: folded to its 8th, 500 ms again)
tp = prog(0, [("DLY_FB", 55), ("DLY_MIX", 60), ("SPREAD", 64)]) + TO_BBD
riff = [33, 33, 45, 33, 36, 33, 31, 33]
tp += sum((note(T0 + 300 + 250 * i, riff[i % 8], 200) for i in range(48)), [])
tp += [f"{T0 + 400 + 500 * i} btn 13" for i in range(4)]
tp += [f"{T0 + 4400 + 375 * i} btn 13" for i in range(4)]
tp += [f"{T0 + 8400 + 1000 * i} btn 13" for i in range(3)]
tp += [f"{T0 + 2200} expect param {P['ALLEY']} 115", f"{T0 + 2200} expect param {P['FINE']} 66",
       f"{T0 + 6000} expect param {P['ALLEY']} 107", f"{T0 + 10500} expect param {P['ALLEY']} 115"]
write("tap_bass", tp, T0 + 15000)

# the knob while the repeats ring: KNOB 1 (encoder 2) on the BBD page, one ALLEY step every 80 ms (3.5 % a step)
def knob(t, steps, every=80):
    out = []
    d = 1 if steps > 0 else -1
    for _ in range(abs(steps)):
        out.append(f"{t} enc 2 {d}"); t += every
    return out, t

lines, _ = SOURCES["lead"]
sw = lines + settings("long") + [f"{T0 + 1} param {P['DLY_FB']} 95", f"{T0 + 1} param {P['ALLEY']} 90"] + TO_BBD
k1, t = knob(T0 + 1200, -30)
k2, t = knob(t + 600, 30)
write("sweep_lead", sw + k1 + k2, T0 + 9000)
# the runaway twisted: the stab once at FEEDBK 124, then ALLEY swept down and up while it sings (the spaceship)
lines, _ = SOURCES["stab"]
sw = [l for l in lines if int(l.split()[0]) < T0 + 2000] + settings("runaway") + TO_BBD
k1, t = knob(T0 + 2500, -40, 60)
k2, t = knob(t + 800, 55, 60)
write("sweep_runaway", sw + k1 + k2 + [f"{t + 1500} param {P['DLY_FB']} 100"], t + 6000)
print("scripts written to", HERE)
