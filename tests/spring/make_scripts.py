"""Writes the host scripts for the DRAIN listening kit (listen/spring/): five sources x six spring settings (and dry),
the same bytes on the old plate for an A/B, the WHOLE Psych Chain (GROWL -> output stage -> ALLEY -> DRAIN -> CHEW) on
four sources at three strengths (each also without DRAIN, and on the build before the re-voice), and the spring's
knobs turned on SPRING + (SELECT held) while it rings. Parameter numbers are the obv_params.h enum. Every source
starts at 2600 ms (after the 2.4 s splash). The kit's other half is tests/spring/render.sh."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
P = dict(O1_WAVE=0, O1_PW=1, O2_WAVE=4, NOISE=3, CUTOFF=12, RESO=13, FENV_AMT=14, FD=21, FS_=22, AA=24, AD=25, AS=26,
         AR=27, MODE=38, GROWL=54, DLY_TIME=55, DLY_FB=56, DLY_TONE=57, DLY_MIX=58, SIZE=59, DAMP=60, PRE=61, DRAIN=62,
         CHEW=64, ALLEY=68, FINE=69, SPREAD=70)
T0 = 2600


def prog(n, params):                         # program change, then the params 1 ms later (before any audio block);
    base = [("GROWL", 0), ("DLY_MIX", 0), ("DRAIN", 0), ("CHEW", 0)]   # every effect off unless the render sets it
    return [f"{T0} midi 0xC0 {n} 0"] + [f"{T0 + 1} param {P[k]} {v}" for k, v in base + params]


def note(t, n, dur, vel=100):
    return [f"{t} midi 0x90 {n} {vel}", f"{t + dur} midi 0x80 {n} 0"]


SOURCES = {
    # a short Cmaj7 stab, twice (INIT, POLY: two detuned saws a voice), room between for the tail
    "stab": (prog(31, [("CUTOFF", 90), ("RESO", 10), ("FENV_AMT", 64), ("AS", 127), ("AR", 30)])
             + sum((note(T0 + 100, n, 150) for n in (48, 52, 55, 59)), [])
             + sum((note(T0 + 2600, n, 150) for n in (48, 52, 55, 59)), []), 7600),
    # program 1 Red Pill as voiced: one bar of the GROWL / CHEW / ALLEY kits' 8th-note riff on A1, then silence
    "bass": (prog(0, []) + sum((note(T0 + 100 + 250 * i, n, 200) for i, n in
                                enumerate([33, 33, 45, 33, 36, 33, 31, 33])), []), 7600),
    # a bright mono lead, filter wide open: G5 A5 C6 short, then E5
    "lead": (prog(31, [("MODE", 3), ("CUTOFF", 127), ("RESO", 5), ("FENV_AMT", 64), ("AS", 127), ("AR", 30)])
             + note(T0 + 100, 79, 180) + note(T0 + 400, 81, 180) + note(T0 + 700, 84, 350) + note(T0 + 2600, 76, 250),
             7600),
    # the spring's own test: a staccato pluck, a surf figure (E4 E4 G4 A4 .. B4 A4), mono, a short filter envelope
    "pluck": (prog(31, [("MODE", 3), ("O1_WAVE", 2), ("O1_PW", 40), ("O2_WAVE", 1), ("CUTOFF", 70), ("RESO", 25),
                        ("FENV_AMT", 110), ("FD", 35), ("FS_", 0), ("AD", 45), ("AS", 0), ("AR", 25)])
              + sum((note(T0 + 100 + 150 * i, n, 90) for i, n in enumerate([64, 64, 67, 69, 0, 71, 69, 0])
                     if n), []) + note(T0 + 2600, 64, 90) + note(T0 + 2750, 52, 400), 7600),
    # program 14 Reef Break as voiced (PERC HIT: noise and a pitched click): a snare's job, twice
    "hit": (prog(13, []) + note(T0 + 100, 60, 80, 120) + note(T0 + 2600, 60, 80, 120), 7600),
}

S = {   # name: (DRAIN, SIZE, DAMP, PRE-DLY, what)
    "boing": (70, 20, 20, 0, "DRAIN 70, SIZE 20 (0.43 s), DAMP 20, no pre-delay: the short tank's flutter"),
    "default": (60, 80, 60, 20, "DRAIN 60 on the patch defaults: SIZE 80 (1.3 s), DAMP 60 (7.5 kHz), PRE-DLY 20 (5 ms)"),
    "splash": (110, 110, 10, 40, "DRAIN 110, SIZE 110 (2.2 s), DAMP 10 (17 kHz), PRE-DLY 40 (11 ms): the drip, wet"),
    "dark": (80, 100, 120, 10, "DRAIN 80, SIZE 100 (1.8 s), DAMP 120 (2.8 kHz): a dull tank"),
    "max": (127, 127, 0, 0, "everything at the top: DRAIN 127, SIZE 127 (3.0 s), DAMP open, no pre-delay"),
}


def settings(name):
    d, sz, dp, pr, _ = S[name]
    return [f"{T0 + 2} param {P['SIZE']} {sz}", f"{T0 + 2} param {P['DAMP']} {dp}", f"{T0 + 2} param {P['PRE']} {pr}",
            f"{T0 + 2} param {P['DRAIN']} {d}"]


def write(name, lines, end):                 # the host reads events in file order: sort by time (stable)
    lines = sorted(lines, key=lambda l: int(l.split()[0]))
    with open(os.path.join(HERE, name + ".txt"), "w") as f:
        f.write("# generated by tests/spring/make_scripts.py\n" + "\n".join(lines) + f"\n{end} end\n")


for src, (lines, end) in SOURCES.items():
    write(f"src_{src}_dry", lines, end)
    for s in S:
        write(f"src_{src}_{s}", lines + settings(s), end)
    for s in ("default", "splash"):          # the same bytes on the old plate (the build before the re-voice)
        write(f"old_{src}_{s}", lines + settings(s), end)

# the whole chain, as it will be played: GROWL -> output stage -> ALLEY -> DRAIN -> CHEW
CHAIN = {   # name: ([(param, value)], what)
    "mild": ([("GROWL", 40), ("DLY_FB", 50), ("DLY_MIX", 45), ("DRAIN", 60), ("SIZE", 80), ("DAMP", 60), ("PRE", 20),
              ("CHEW", 40)], "GROWL 30 %, ALLEY SYNC 1/8. FEEDBK 50 MIX 45, the default spring at DRAIN 60, CHEW 30 %"),
    "surf": ([("GROWL", 64), ("ALLEY", 65), ("DLY_FB", 15), ("DLY_TONE", 100), ("DLY_MIX", 80), ("SPREAD", 0),
              ("DRAIN", 110), ("SIZE", 110), ("DAMP", 10), ("PRE", 40), ("CHEW", 64)],
             "GROWL 50 %, ALLEY 90 ms slap (mono), the splash spring at DRAIN 110, CHEW 50 %"),
    "mangle": ([("GROWL", 127), ("ALLEY", 101), ("DLY_FB", 124), ("DLY_TONE", 90), ("DLY_MIX", 60), ("SPREAD", 64),
                ("DRAIN", 127), ("SIZE", 127), ("DAMP", 0), ("PRE", 0), ("CHEW", 127)],
               "everything at the top: GROWL 100 %, ALLEY 300 ms runaway (FEEDBK 124), DRAIN / SIZE 127, CHEW 100 %"),
}
for src in ("stab", "bass", "lead", "pluck"):
    lines, end = SOURCES[src]
    for nm, (ps, _) in CHAIN.items():
        ex = [f"{T0 + 2} param {P[k]} {v}" for k, v in ps]
        write(f"chain_{src}_{nm}", lines + ex, end)
        write(f"chain_{src}_{nm}_nodrain", lines + ex + [f"{T0 + 3} param {P['DRAIN']} 0"], end)   # what DRAIN adds
        write(f"oldchain_{src}_{nm}", lines + ex, end)   # the same bytes on the build before (old plate, old routing)

# the knobs while it rings, on the panel: FX x3 = SPRING, SELECT held = SPRING + (KNOB 1 SIZE, 2 DAMP, 3 PRE-DLY;
# encoders 2, 3, 4), one detent (2 steps) every 40 ms. The pluck figure looped under it
TO_SPRING = [f"{T0 + 20} btn 2", f"{T0 + 60} btn 2", f"{T0 + 100} btn 2", f"{T0 + 200} expect page 13"]


def turns(t, enc, detents, every=40):
    out, d = [], 1 if detents > 0 else -1
    for _ in range(abs(detents)):
        out.append(f"{t} enc {enc} {d}"); t += every
    return out, t


lines, _ = SOURCES["pluck"]
loop = [l for l in lines if " midi 0x9" not in l and " midi 0x8" not in l]
fig = [64, 64, 67, 69, 0, 71, 69, 0]
for i in range(56):
    if fig[i % 8]: loop += note(T0 + 300 + 150 * i, fig[i % 8], 90)
for knob, enc, start in (("size", 2, (60, 0, 60, 20)), ("damp", 3, (80, 100, 0, 20)), ("pre", 4, (80, 90, 30, 0))):
    d, sz, dp, pr = start
    sw = loop + [f"{T0 + 2} param {P['DRAIN']} {d}", f"{T0 + 2} param {P['SIZE']} {sz}",
                 f"{T0 + 2} param {P['DAMP']} {dp}", f"{T0 + 2} param {P['PRE']} {pr}"] + TO_SPRING
    sw += [f"{T0 + 900} btndown 3"]
    k1, t = turns(T0 + 1000, enc, 64)        # up the whole range in 2.6 s
    k2, t = turns(t + 400, enc, -64)         # and back
    k3, t = turns(t + 400, enc, 64, 10)      # and up again, fast (a flick)
    write(f"sweep_{knob}", sw + k1 + k2 + k3 + [f"{t + 200} btnup 3"], T0 + 12000)
# the same turns over a held, dark pad (INIT, LP 24 nearly closed: nothing above ~2 kHz in the dry), for the
# measurement: a click is broadband, so anything above 10 kHz in these is one (tests/spring/analyze.py)
pad = prog(31, [("CUTOFF", 45), ("RESO", 0), ("FENV_AMT", 64), ("AA", 30), ("AS", 127), ("AR", 60)])
pad = [l for l in pad if int(l.split()[0]) <= T0 + 1] + [f"{T0 + 300} midi 0x90 57 90", f"{T0 + 300} midi 0x90 64 90",
                                                        f"{T0 + 11000} midi 0x80 57 0", f"{T0 + 11000} midi 0x80 64 0"]
for knob, enc, start in (("size", 2, (90, 0, 60, 20)), ("damp", 3, (90, 100, 0, 20)), ("pre", 4, (90, 90, 30, 0))):
    d, sz, dp, pr = start
    sw = pad + [f"{T0 + 2} param {P['DRAIN']} {d}", f"{T0 + 2} param {P['SIZE']} {sz}",
                f"{T0 + 2} param {P['DAMP']} {dp}", f"{T0 + 2} param {P['PRE']} {pr}"] + TO_SPRING + [f"{T0 + 900} btndown 3"]
    k1, t = turns(T0 + 1000, enc, 64); k2, t = turns(t + 400, enc, -64); k3, t = turns(t + 400, enc, 64, 10)
    write(f"sweepm_{knob}", sw + k1 + k2 + k3 + [f"{t + 200} btnup 3"], T0 + 12000)
    write(f"sweepm_{knob}_still", sw, T0 + 12000)          # the same pad, no turns: what the pad itself scores
# the jumps, as MIDI CC would send them: SIZE / DAMP / PRE-DLY end to end while the splash spring rings after the hit
lines, _ = SOURCES["hit"]
jl = [l for l in lines if int(l.split()[0]) < T0 + 2000] + settings("splash")
for i, (p, v) in enumerate([("SIZE", 0), ("SIZE", 127), ("DAMP", 127), ("DAMP", 0), ("PRE", 127), ("PRE", 0)]):
    jl.append(f"{T0 + 400 + 250 * i} param {P[p]} {v}")
write("jumps_hit", jl, T0 + 5000)
print("scripts written to", HERE)
