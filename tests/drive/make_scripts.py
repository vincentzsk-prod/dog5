"""Writes the host scripts for the GROWL listening kit (listen/drive/) and its measurements.
Four sources x GROWL 0/25/50/75/100 % (raw 0, 32, 64, 95, 127), plus a knob sweep. Parameter numbers are the
obv_params.h enum (54 = GROWL, the old chorus mix slot). Every source starts at 2600 ms (after the 2.4 s splash)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
GROWL = {0: 0, 25: 32, 50: 64, 75: 95, 100: 127}
P = dict(O1_WAVE=0, O2_WAVE=4, O2_FINE=11, CUTOFF=12, RESO=13, FENV_AMT=14, FTYPE=16, AA=24, AS=26, AR=27, MODE=38,
         GLIDE=41, DLY_MIX=58, REV_MIX=62, GROWL=54)
T0 = 2600
def prog(n, params):                      # program change, then the params 1 ms later (before any audio block)
    return [f"{T0} midi 0xC0 {n} 0"] + [f"{T0 + 1} param {P[k]} {v}" for k, v in params]
def note(t, n, dur, vel=100):
    return [f"{t} midi 0x90 {n} {vel}", f"{t + dur} midi 0x80 {n} 0"]
SOURCES = {
    # one plain saw, low: C2. INIT with OSC 2 off, the filter open-ish, no envelope on it, full sustain
    "lowsaw": (prog(31, [("O2_WAVE", 0), ("CUTOFF", 110), ("RESO", 0), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
               + note(T0 + 100, 36, 3000), 6500),
    # a held Cmaj7 in the middle, two detuned saws a voice (INIT, POLY)
    "chord": (prog(31, [("CUTOFF", 90), ("RESO", 10), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
              + sum((note(T0 + 100, n, 3000) for n in (48, 52, 55, 59)), []), 6500),
    # program 1 Red Pill as voiced (MONO, saw + pulse an octave up, its own pre-filter DRIVE 40): an 8th-note riff
    "bass": (prog(0, []) + sum((note(T0 + 100 + 250 * i, n, 200) for i, n in
                                enumerate([33, 33, 45, 33, 36, 33, 31, 33] * 2)), []), 7500),
    # a bright mono lead, filter wide open: G5 A5, then C6 held 2 s (the aliasing window), E5
    "lead": (prog(31, [("MODE", 3), ("CUTOFF", 127), ("RESO", 5), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
             + note(T0 + 100, 79, 300) + note(T0 + 400, 81, 300) + note(T0 + 700, 84, 2000) + note(T0 + 2700, 76, 400),
             6500),
}
def write(name, lines, end):                 # the host reads events in file order: sort by time (stable)
    lines = sorted(lines, key=lambda l: int(l.split()[0]))
    with open(os.path.join(HERE, name + ".txt"), "w") as f:
        f.write("# generated by tests/drive/make_scripts.py\n" + "\n".join(lines) + f"\n{end} end\n")
for src, (lines, end) in SOURCES.items():
    for pct, raw in GROWL.items():
        write(f"src_{src}_{pct:03d}", lines + [f"{T0 + 1} param {P['GROWL']} {raw}"], end)
# the knob: the chord held 9 s on the DRIVE page while GROWL is turned 0 -> 100 % -> 0 one detent at a time
# (encoder 2 = KNOB 1, one detent = 2 steps; FX button = 2 shows the DRIVE page)
sw, end = SOURCES["chord"][0][:], 0
sw = [l for l in sw if " midi 0x80 " not in l] + [f"{T0 + 9100} midi 0x80 {n} 0" for n in (48, 52, 55, 59)]
sw += [f"{T0 + 50} btn 2"]
t = T0 + 600
for i in range(64): sw.append(f"{t} enc 2 1"); t += 60
t += 500
for i in range(64): sw.append(f"{t} enc 2 -1"); t += 60
write("sweep_chord", sw, T0 + 10500)
# the same sweep on the bright lead's held C6
sw = prog(31, [("MODE", 3), ("CUTOFF", 127), ("RESO", 5), ("FENV_AMT", 64), ("AS", 127), ("AR", 40)])
sw += [f"{T0 + 50} btn 2", f"{T0 + 100} midi 0x90 84 100", f"{T0 + 9100} midi 0x80 84 0"]
t = T0 + 600
for i in range(64): sw.append(f"{t} enc 2 1"); t += 60
t += 500
for i in range(64): sw.append(f"{t} enc 2 -1"); t += 60
write("sweep_lead", sw, T0 + 10500)
# the aliasing proof: one saw (OSC 2 off, VINTAGE 0: an exact harmonic comb), the filter wide open, MONO, a high note
# held 3 s at GROWL 0 and 100 %: C6 (1046.5 Hz) and C7 (2093 Hz)
for nm, n in (("c6", 84), ("c7", 96)):
    base = prog(31, [("MODE", 3), ("O2_WAVE", 0), ("CUTOFF", 127), ("RESO", 0), ("FENV_AMT", 64), ("AS", 127),
                     ("AR", 40)]) + [f"{T0 + 1} param 42 0"] + note(T0 + 100, n, 3000)
    for pct in (0, 100):
        write(f"alias_{nm}_{pct:03d}", base + [f"{T0 + 1} param {P['GROWL']} {GROWL[pct]}"], T0 + 3600)
# the hardest the voices can drive it: 8-voice unison saws at VOLUME 127, the filter open, BIAS 127, TONE 0, then a
# POLY cluster of 8; GROWL stepped through every value (for the sanitizer build: no overflow anywhere)
w = prog(31, [("MODE", 2), ("CUTOFF", 127), ("RESO", 0), ("FENV_AMT", 64), ("AS", 127)]) + [
    f"{T0 + 1} param 39 8", f"{T0 + 1} param 45 127", f"{T0 + 1} param 52 127", f"{T0 + 1} param 53 0"]
w += note(T0 + 100, 36, 3300)
w += [f"{T0 + 3500} param 38 0"] + sum((note(T0 + 3600, n, 3000) for n in (36, 43, 48, 52, 55, 60, 64, 67)), [])
w += [f"{T0 + 100 + 50 * i} param {P['GROWL']} {i % 128}" for i in range(130)]
write("worst_voices", w, T0 + 7000)
print("scripts written to", HERE)
