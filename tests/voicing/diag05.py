"""Round 2 of 05 ZEAROX, step 1: DIAGNOSIS (before anything is changed).

  python3 tests/voicing/diag05.py            -> prints the tables and writes listen/voicing/batch-03b/round2/diagnosis.md

(1) why round-1 B / C (listen/voicing/batch-03b/05-zearox/results.json) read as muddy: time windows 0-20 / 20-100 / 100-300 ms of the isolated A1 hit,
    the band split, the 150-400 Hz share against the 1.2 kHz+ share, the tail to -60 dB with the DC subtracted, GROWL 104 and CHEW 127 separately;
(2) what makes 07 Tape Splice C 'glitchy and pixelated': C exactly, C without the tape, and C with X-MOD / the pitch LFO / the tape / the pulse waves changed one at
    a time, on the kick phrase m (VOLUME re-trimmed to the bank reference) and on the splice phrase n.

New measures (batch03b_metrics.py): TWO-LEVEL = the share of samples within 10 % of the rail (the local peak of each 5 ms window) over the first 100 ms of a hit
(a hard-clipped square: near 100 %; a sine: about 15 %; a decaying body lowers it), PIXEL = the share of the energy above 1.2 kHz and the spectral flatness
(geometric / arithmetic mean of the power spectrum, 100 Hz - 10 kHz) of the first 100 ms: 1 = white, 0 = a few lines."""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import voicekit as K
import batch02a as B2
import batch02a_metrics as M
import batch03a_metrics as N
import batch03b_metrics as Q
from batch03b_variants import PATCHES

OUT = os.path.join(K.ROOT, "listen", "voicing", "batch-03b", "round2")
R1 = json.load(open(os.path.join(K.ROOT, "listen", "voicing", "batch-03b", "05-zearox", "results.json")))["variants"]
R7 = json.load(open(os.path.join(K.ROOT, "listen", "voicing", "batch-03b", "07-tape-splice", "results.json")))["variants"]
SPEC5 = [p for p in PATCHES if p["slot"] == 5][0]
exe = None


def two_level(a, t_on, span=(0, 100), win=5.0, thr=0.9):
    """share of samples (mid channel) with |x| >= thr x the rail, the rail being the largest |x| of each 5 ms window, over [t0 + span]"""
    x = a.mean(1)[Q._s(t_on + span[0]):Q._s(t_on + span[1])]
    w = int(K.FS * win / 1000)
    n = len(x) // w
    s = []
    for i in range(n):
        seg = np.abs(x[i * w:(i + 1) * w])
        pk = seg.max()
        if pk > 32767 * 10 ** (-50 / 20):
            s.append((seg >= thr * pk).mean())
    return float(100 * np.mean(s)) if s else float("nan")


def flatness(a, t_on, span=(0, 100), lo=100, hi=10000):
    x = a.mean(1)[Q._s(t_on + span[0]):Q._s(t_on + span[1])]
    P = np.abs(np.fft.rfft(x * np.hanning(len(x)), 8192)) ** 2
    f = np.fft.rfftfreq(8192, 1 / K.FS)
    P = P[(f >= lo) & (f <= hi)] + 1e-9
    return float(np.exp(np.log(P).mean()) / P.mean())


def hit_row(a, t_nom, key_up_ms=150):
    t0 = Q.onset(a, t_nom)
    wins = [Q.bsplit(a, t0 + x0, t0 + x1) for x0, x1 in ((0, 20), (20, 100), (100, 300))]
    dc = a[Q._s(t_nom + 900):Q._s(t_nom + 1200)].mean(0)
    tail = M.tail_times(a, t_nom + key_up_ms, 60, 900, dc=dc)
    hf = Q.share_above(wins[0], 4)
    return {"wins": wins, "r_mud": [w[2] / max(w[4], 0.1) for w in wins], "tail60": tail["t60"], "tail40": tail["t40"], "two": two_level(a, t0), "hf20": hf,
            "hf100": float(sum(Q.bsplit(a, t0, t0 + 100)[4:])), "flat": flatness(a, t0)}


def trim_on_m(params):
    v, _ = B2.trim_volume(exe, SPEC5, params)
    return {**params, "VOLUME": v}, v


def main():
    global exe
    exe = K.build_host()
    os.makedirs(OUT, exist_ok=True)
    L = ["# 05 ZEAROX round 2: diagnosis (generated by tests/voicing/diag05.py)\n"]
    # ---- (1) round 1 ------------------------------------------------------------------------------------------------------
    L.append("## 1. Why round-1 B / C were muddy: the isolated A1 hit of phrase m\n")
    L.append("Windows from the real onset: 0-20 / 20-100 / 100-300 ms. Band split % <60 / 60-150 / 150-400 / 400-1.2k / 1.2k+. MUD = the 150-400 Hz share divided by the 1.2 kHz+ share "
             "(higher = more body, less edge). TAIL = ms from the key-up (150 ms) to -40 / -60 dB, DC subtracted. TWO-LEVEL, HF and FLAT: see the module doc.\n")
    L.append("| variant | VOLUME | split 0-20 | split 20-100 | split 100-300 | MUD 0-20 / 20-100 / 100-300 | tail -40 / -60 dB | two-level % | >1.2k % (0-100 ms) | flatness |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    rows = [("round-1 B (GROWL 104, CHEW 127)", R1["B"]["params"]), ("round-1 C (click-led)", R1["C"]["params"])]
    rows += [("B, GROWL 0", {**R1["B"]["params"], "GROWL": 0}), ("B, CHEW 0", {**R1["B"]["params"], "CHEW": 0}), ("B, GROWL 0 + CHEW 0", {**R1["B"]["params"], "GROWL": 0, "CHEW": 0}),
             ("A original", R1["A"]["params"])]
    D1 = {}
    for nm, p in rows:
        a = K.render(exe, "m_kick", params=p, tag="dg")[0]
        r = hit_row(a, 4500)
        D1[nm] = r
        L.append(f"| {nm} | {p['VOLUME']} | " + " | ".join(Q.fmt_list(w) for w in r["wins"]) + " | " + " / ".join(f"{v:.1f}" for v in r["r_mud"]) +
                 f" | {r['tail40']:.0f} / {r['tail60']:.0f} | {r['two']:.0f} | {r['hf100']:.1f} | {r['flat']:.4f} |")
    L.append("")
    # ---- (2) 07 C ----------------------------------------------------------------------------------------------------------
    C = R7["C"]["params"]
    L.append("## 2. What carries the glitch in 07 Tape Splice C\n")
    L.append("07 C exactly (X-MOD 100, pitch LFO 22, PULSE waves, CHEW 127, DROPS 110) and one element changed at a time (each from C or from C without the tape). "
             "Phrase m: VOLUME re-trimmed to -18.0 on the 11 hits (so the loudness is equal); phrase n: the held A2 (6.0-8.4 s) pitch s.d. (cents), dips of 6 dB or more (n . deepest dB), and the same two-level / HF numbers.\n")
    L.append("| variant | VOLUME on m | m: A1 two-level % | m: >1.2k % (0-100 ms) | m: flatness | m: crest 30 ms | m: tail -60 (ms) | m: CPU idle | n: pitch s.d. cents | n: dips | n: two-level % (held A2) | n: >1.2k % |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    notape = {**C, "CHEW": 0, "TP_DROPS": 0, "TP_HISS": 0}
    cases = [("C exact", C), ("C, tape off (CHEW 0, DROPS 0)", notape), ("C, X-MOD 0", {**C, "XMOD": 0}), ("C, pitch LFO 0", {**C, "LFO_PITCH": 0}),
             ("C, saw + saw (waves)", {**C, "O1_WAVE": 1, "O2_WAVE": 1}),
             ("C no tape, X-MOD 0", {**notape, "XMOD": 0}), ("C no tape, pitch LFO 0", {**notape, "LFO_PITCH": 0}), ("C no tape, saw + saw", {**notape, "O1_WAVE": 1, "O2_WAVE": 1}),
             ("C no tape, X-MOD 0 + LFO 0", {**notape, "XMOD": 0, "LFO_PITCH": 0}),
             ("07 B (X-MOD 70, LFO 16, CHEW 80)", R7["B"]["params"])]
    D2 = {}
    for nm, p in cases:
        pm, v = trim_on_m(p)
        am = K.render(exe, "m_kick", params=pm, tag="dg")[0]
        rm = hit_row(am, 4500)
        an = K.render(exe, "n_splice", params=p, tag="dg2")[0]
        w = Q.wobble(an, 110.0, 6000, 8400)
        dp = M.dips(an, 6200, 8300)
        t0 = 6000
        two_n = two_level(an, t0 + 200, span=(0, 1500))
        hf_n = float(sum(Q.bsplit(an, 6200, 8300)[4:]))
        ci = K.callgrind_ips(CG, "x_stress", params=pm, tag="dgx", notes=False)
        idle = ci[0] / ci[1]
        D2[nm] = dict(vol=v, two=rm["two"], hf=rm["hf100"], flat=rm["flat"], idle=idle)
        L.append(f"| {nm} | {v} | {rm['two']:.0f} | {rm['hf100']:.1f} | {rm['flat']:.4f} | {N.crest_db(am, t0_ms=Q.onset(am, 4500), t1_ms=Q.onset(am, 4500) + 30):.1f} | {rm['tail60']:.0f} | {idle:.0f} | "
                 f"{w['sd']:.1f}{'' if w['kept'] > 0.9 else ' (kept ' + format(100 * w['kept'], '.0f') + ' %)'} | {dp[1]} . {dp[0]:.0f} | {two_n:.0f} | {hf_n:.1f} |")
    L.append("")
    open(os.path.join(OUT, "diagnosis.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


CG = None
if __name__ == "__main__":
    if "--no-cost" not in sys.argv:
        CG = K.callgrind_exe()
    main()
